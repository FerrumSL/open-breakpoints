# Checks on a drafted EUCAST year, and the files for review.
# Usage: Rscript R/report_eucast.R <work_dir> <year> <new_table> <next_year>
#   new_table: the sheet whose rows WHONET's file lacks for <year>; its rows become
#   data/breakpoints/EUCAST/<year>.tsv. Rows of the other mapped sheets are only used to
#   check the method against the rows WHONET already has.
# Writes data/breakpoints/EUCAST/<year>.tsv, review/EUCAST_<year>_flags.tsv,
# review/EUCAST_<year>_report.md.

source("R/common.R")
source("R/compare_extractions.R")

args <- commandArgs(trailingOnly = TRUE)
stopifnot(length(args) == 4)
work <- args[1]; year <- args[2]; new_table <- args[3]; next_year <- args[4]

tables <- read_tsv("maps/eucast_tables.tsv")
rows <- read_tsv(file.path(work, "rows.tsv"))
flags <- read_tsv(file.path(work, "flags.tsv"))
whonet <- read_tsv("sources/whonet/Breakpoints.txt")
whonet <- whonet[whonet$GUIDELINES == "EUCAST" & whonet$BREAKPOINT_TYPE == "Human", ]

key <- function(d) trimws(paste(d$ORGANISM_CODE, d$WHONET_TEST, d$SITE_OF_INFECTION))
val <- function(d) sprintf("R %s, I %s, S %s%s", d$R, ifelse(d$I == "", "(none)", d$I), d$S,
                           ifelse(d$POTENCY == "", "", paste0(", ", d$POTENCY)))
md <- function(x) {
  if (nrow(x) == 0) return("None.")
  c(paste("|", paste(names(x), collapse = " | "), "|"),
    paste("|", paste(rep("---", ncol(x)), collapse = " | "), "|"),
    apply(x, 1, function(r) paste("|", paste(r, collapse = " | "), "|")))
}

# 1. Two extractions, for the mapped sheets.
cmp <- compare(read_tsv(file.path(work, "xls_cells.tsv")), read_tsv(file.path(work, "pdf_cells.tsv")))
in_scope <- sum(cmp$matched_sheets %in% tables$sheet)
# Value lines of the PDF that could not be read as a drug line, for the mapped sheets.
pdf_rows <- read_tsv(file.path(work, "pdf_cells.tsv"))
lost <- read_tsv(file.path(work, "pdf_cells_dropped.tsv"))
sheet_names <- unique(read_tsv(file.path(work, "xls_cells.tsv"))$sheet)
lost_sheet <- sheet_names[as.integer(pdf_rows$table_no[match(lost$title, pdf_rows$title)])]
n_lost <- sum(lost_sheet %in% tables$sheet)
diffs <- if (is.null(cmp$diffs)) 0 else sum(cmp$diffs$sheet %in% tables$sheet)

# 2. Method check: sheets whose rows WHONET already has for this year.
other <- tables$ORGANISM_CODE[tables$sheet != new_table]
a <- rows[rows$REFERENCE_TABLE != new_table, ]
b <- whonet[whonet$YEAR == year & whonet$ORGANISM_CODE %in% other, ]
stopifnot(!anyDuplicated(key(a)), !anyDuplicated(key(rows[rows$REFERENCE_TABLE == new_table, ])))
m <- match(key(a), key(b))
same1 <- sum(!is.na(m) & val(a) == val(b)[m])
unmatched1 <- sum(!(key(b) %in% key(a)))

# 3. New rows against WHONET's rows for the next year.
n <- rows[rows$REFERENCE_TABLE == new_table, ]
w <- whonet[whonet$YEAR == next_year & whonet$REFERENCE_TABLE == new_table, ]
m2 <- match(key(n), key(w))
same2 <- !is.na(m2) & val(n) == val(w)[m2]
changed <- data.frame(Row = key(n), `This year` = val(n), `Next year` = val(w)[m2],
                      check.names = FALSE)[!is.na(m2) & !same2, ]
only_new <- data.frame(Row = key(n), Values = val(n))[is.na(m2), ]
only_next <- data.frame(Row = key(w), Values = val(w))[!(key(w) %in% key(n)), ]

dir.create("data/breakpoints/EUCAST", recursive = TRUE, showWarnings = FALSE)
write.table(n, sprintf("data/breakpoints/EUCAST/%s.tsv", year), sep = "\t", quote = FALSE,
            row.names = FALSE, na = "", fileEncoding = "UTF-8")
f <- flags[flags$sheet == new_table, ]
write.table(f, sprintf("review/EUCAST_%s_flags.tsv", year), sep = "\t", quote = FALSE,
            row.names = FALSE, na = "", fileEncoding = "UTF-8")

src <- read_tsv("data/sources.tsv")
src <- src[src$GUIDELINES == "EUCAST" & src$YEAR == year, c("SOURCE_ID", "VERSION", "URL", "SHA256")]
lines <- c(
  sprintf("# EUCAST %s, table %s: draft rows and checks", year, new_table),
  "",
  sprintf("Generated by `make eucast-%s`. Status of every row: `draft`. The comparison of the rows with", year),
  "the source document by people is not finished, and no clinical reviewer has seen the flagged cases.",
  "",
  sprintf("The row layout (sites, organism level, drug codes) follows WHONET's EUCAST %s rows. WHONET's", next_year),
  "later years write some of these lines differently; which layout is wanted is open (questions 1",
  "and 2 in the questions file). The values do not depend on it.",
  "",
  "## Sources", "", md(src), "",
  "## Check 1: two independent extractions", "",
  sprintf("Excel workbook (Python) against PDF (R, text layout), sheets %s:", toString(tables$sheet)),
  sprintf("%d cells compared, %d differences.", 5 * in_scope, diffs),
  sprintf("Value lines of the PDF that could not be read as a drug line, in these sheets: %d.", n_lost),
  "A cell agrees when the Excel text plus its footnote marks equals the PDF text.",
  "Limit: this check finds reading errors. It cannot confirm where a value ends and its footnote",
  "mark begins, because that split comes from the fonts of the Excel workbook alone. Check 3 and",
  "the check by people cover that.", "",
  "## Check 2: the method reproduces rows WHONET already has", "",
  sprintf("For %s WHONET's file already holds EUCAST %s rows. The same extraction and the same",
          toString(other), year),
  "conversion rules were applied to those sheets and compared with WHONET's rows",
  "(organism, test, site, potency, R, I, S).", "",
  sprintf("Our rows: %d. WHONET's rows: %d. Identical: %d. WHONET rows without a row of ours: %d.",
          nrow(a), nrow(b), same1, unmatched1),
  "Limit: the conversion rules were read from WHONET's own rows, these among them, and the disk",
  "labels are looked up in WHONET's file. The check confirms the extraction and the arithmetic.",
  "These sheets have no infection-site or species-specific lines, so it does not test those rules.", "",
  sprintf("## Check 3: new %s rows against WHONET's %s rows", new_table, next_year), "",
  sprintf("New rows: %d. WHONET %s rows for the table: %d. Identical: %d.",
          nrow(n), next_year, nrow(w), sum(same2)), "",
  "Values that differ (each must match a revision that EUCAST lists for the next version):", "",
  md(changed), "",
  sprintf("Rows only in the new %s draft:", year), "", md(only_new), "",
  sprintf("Rows only in WHONET %s:", next_year), "", md(only_next), "",
  "## Review list", "",
  sprintf("%d flagged cases in `review/EUCAST_%s_flags.tsv` (footnotes, site qualifiers, cells without",
          nrow(f), year),
  sprintf("numbers, organism restrictions). Questions on conventions: `review/EUCAST_%s_questions.md`.", year))
writeLines(lines, sprintf("review/EUCAST_%s_report.md", year))
cat(sprintf("extractions: %d cells, %d differences | method check: %d of %d identical | new rows: %d, %d identical to %s, %d flags\n",
            5 * in_scope, diffs, same1, nrow(a), nrow(n), sum(same2), next_year, nrow(f)))
